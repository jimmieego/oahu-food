const ROAD_KINDS = ['other', 'minor', 'link', 'major', 'highway'];

function repeat(prefix, suffix, color) {
    return Object.fromEntries(ROAD_KINDS.map((kind) => [`${prefix}${kind}${suffix}`, color]));
}

